import { FoodItem, AgePrepGuide, AllergenId, ChokingRisk, FoodCategory } from '../types';

function makeFood(
  id: string,
  name: string,
  emoji: string,
  category: FoodCategory,
  opts: {
    minAgeMonths?: number;
    ironRich?: boolean;
    gentleOnTummy?: boolean;
    chokingRisk?: ChokingRisk;
    chokingNotes: string;
    allergens?: AllergenId[];
    nutritionHighlights: string[];
    prep6to8: { blw: string; puree: string; cutSize: string; texture: string };
    prep9to11: { blw: string; puree: string; cutSize: string; texture: string };
    prep12Plus: { blw: string; puree: string; cutSize: string; texture: string };
    pairings: string[];
    lists?: string[];
  }
): FoodItem {
  const prepByAge: AgePrepGuide[] = [
    { stage: '6-8m', ...opts.prep6to8 },
    { stage: '9-11m', ...opts.prep9to11 },
    { stage: '12m+', ...opts.prep12Plus },
  ];
  return {
    id,
    name,
    emoji,
    category,
    minAgeMonths: opts.minAgeMonths ?? 6,
    ironRich: opts.ironRich ?? false,
    gentleOnTummy: opts.gentleOnTummy ?? false,
    chokingRisk: opts.chokingRisk ?? 'low',
    chokingNotes: opts.chokingNotes,
    allergens: opts.allergens ?? [],
    nutritionHighlights: opts.nutritionHighlights,
    prepByAge,
    pairings: opts.pairings,
    lists: opts.lists ?? ['First 100 Foods'],
  };
}

